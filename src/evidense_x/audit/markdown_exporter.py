"""Publication-ready Markdown audit certificate generator."""
from typing import Dict, Any

def export_audit_to_markdown(results: Dict[str, Any], dataset_title: str) -> str:
    """Generates formatted GitHub Markdown compliance audit badge and table."""
    status_badge = "✅ CERTIFIED CLEAN" if results.get("exact_leakage_count", 0) == 0 else "⚠️ LEAKAGE DETECTED"
    md = f"""# Data Quality & Leakage Audit Certificate: {dataset_title}

**Status:** {status_badge}

## Quantitative Audit Metrics

| Metric Identifier | Value | Tolerance Threshold | Status |
| :--- | :--- | :--- | :--- |
| **Exact Record Contamination** | `{results.get('exact_leakage_count', 0)}` | `0` | {'Pass' if results.get('exact_leakage_count', 0) == 0 else 'Fail'} |
| **Near-Duplicate Overlap Rate** | `{results.get('near_leakage_rate', 0.0):.4f}` | `0.0100` | {'Pass' if results.get('near_leakage_rate', 0.0) < 0.01 else 'Review'} |
| **Adversarial Partition AUC** | `{results.get('adversarial_auc', 0.5):.3f}` | `0.6500` | {'Pass' if results.get('adversarial_auc', 0.5) <= 0.65 else 'Shift Detected'} |

*Generated by Evidense-X Automated Auditing Engine.*
"""
    return md
